"""Dataset discovery: profile every table the configured MySQL user can read (and any CSVs passed on the command line)
WITHOUT assuming a schema. Writes results/data_profile.md and results/data_profile.json.

    python data/profile_data.py                      # all readable MySQL tables
    python data/profile_data.py path/to/file.csv ... # also profile CSVs
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import config  # noqa: E402
from database.connection import query  # noqa: E402

MAX_ROWS = 200_000
ROLE_PATTERNS = {
    "user_fields": r"user|customer|person|learner|member|account|courier|delivery_person|age|gender",
    "campaign_ad_fields": r"campaign|\bad\b|ad_|advert|impression|click|spend|promo|sponsor|bid|cpc|cpm|ctr|placement|creative",
    "engagement_metrics": r"rating|click|order|session|view|like|engag|time_taken|duration|conversion|purchase|retention|active|count",
    "time_fields": r"date|time|week|day|month|year|period|timestamp",
}


def profile(df: pd.DataFrame, name: str, origin: str) -> dict:
    n = len(df)
    cols = {}
    for c in df.columns:
        s = df[c]
        info = dict(dtype=str(s.dtype), missing=int(s.isna().sum()), missing_pct=round(float(s.isna().mean()) * 100, 2),
                    unique=int(s.nunique(dropna=True)))
        if pd.api.types.is_numeric_dtype(s) and not pd.api.types.is_bool_dtype(s):
            d = s.describe()
            info["distribution"] = {k: (None if pd.isna(d.get(k)) else round(float(d.get(k)), 4)) for k in ["mean", "std", "min", "25%", "50%", "75%", "max"]}
        else:
            vc = s.astype(str).value_counts(dropna=True).head(8)
            info["top_values"] = {k: int(v) for k, v in vc.items()}
        cols[c] = info
    lname = {c: c.lower() for c in df.columns}
    roles = {r: [c for c in df.columns if re.search(p, lname[c])] for r, p in ROLE_PATTERNS.items()}
    roles["time_fields"] = sorted(set(roles["time_fields"]) | {c for c in df.columns if pd.api.types.is_datetime64_any_dtype(df[c])})
    roles["candidate_identifiers"] = [c for c in df.columns if (n and cols[c]["unique"] / n > 0.95) or re.search(r"(^|_)id$", lname[c])]
    kind = "SYNTHETIC (generated by an earlier project)" if re.match(r"(synthetic|simulated|heldout_sim)", name.split(".")[-1]) else \
        "SYNTHETIC (AdLens layer)" if name.split(".")[-1].startswith("adlens_") else "REAL or derived from real (verify against its project README)"
    return dict(name=name, origin=origin, provenance_guess=kind, rows=n, columns=len(df.columns), column_names=list(df.columns), columns_detail=cols,
                roles=roles, has_impressions_and_clicks=bool(re.search("impression", " ".join(lname.values())) and re.search("click", " ".join(lname.values()))))


def mysql_sources():
    t = query("SELECT table_schema, table_name, table_rows FROM information_schema.tables "
              "WHERE table_schema NOT IN ('information_schema','performance_schema','mysql','sys') ORDER BY table_schema, table_name")
    return [(f"{a}.{b}", int(r or 0)) for a, b, r in t.itertuples(index=False)]


def main(csvs):
    out = []
    for name, approx in mysql_sources():
        df = query(f"SELECT * FROM {name} LIMIT {MAX_ROWS}")
        out.append(profile(df, name, f"MySQL (approx {approx} rows; profiled up to {MAX_ROWS})"))
        print("profiled", name, len(df))
    for p in csvs:
        df = pd.read_csv(p, nrows=MAX_ROWS)
        out.append(profile(df, pathlib.Path(p).name, f"CSV {p}"))
        print("profiled", p, len(df))
    (config.RESULTS / "data_profile.json").write_text(json.dumps(out, indent=1, default=str), encoding="utf-8")
    L = ["# Data profile", "", "Generated by `data/profile_data.py`. Provenance is a guess from table names; confirm against each source project.", ""]
    L += ["| table | rows | cols | provenance (guess) | impressions+clicks? | time fields |", "|---|---|---|---|---|---|"]
    L += [f"| {p['name']} | {p['rows']:,} | {p['columns']} | {p['provenance_guess']} | {'yes' if p['has_impressions_and_clicks'] else 'no'} | {', '.join(p['roles']['time_fields']) or '-'} |" for p in out]
    for p in out:
        L += ["", f"## {p['name']}", f"{p['origin']} · {p['rows']:,} rows × {p['columns']} columns · {p['provenance_guess']}", ""]
        for r, v in p["roles"].items():
            L.append(f"- **{r.replace('_', ' ')}:** {', '.join(v) or '-'}")
        L += ["", "| column | dtype | missing % | unique | distribution / top values |", "|---|---|---|---|---|"]
        for c, i in p["columns_detail"].items():
            dist = i.get("distribution") or i.get("top_values")
            L.append(f"| {c} | {i['dtype']} | {i['missing_pct']} | {i['unique']} | {json.dumps(dist)[:140]} |")
    (config.RESULTS / "data_profile.md").write_text("\n".join(L), encoding="utf-8")
    print("wrote", config.RESULTS / "data_profile.md")


if __name__ == "__main__":
    main(sys.argv[1:])
