_IDENT = re.compile(r"^[a-z_]+$")


def get(dataset: str) -> dict:
    if dataset not in DATASETS:
        raise ValueError(f"unknown dataset '{dataset}'. Choose from {list(DATASETS)}")
    return DATASETS[dataset]


def dim_expr(dataset: str, dim: str) -> str:
    d = get(dataset)
    if dim not in d["dims"]:
        raise ValueError(f"unknown dimension '{dim}' for {dataset}. Available: {list(d['dims'])}")
    return f"COALESCE(CAST({d['dims'][dim][0]} AS CHAR), 'unknown')"


def metric(dataset: str, name: str) -> dict:
    d = get(dataset)
    if name not in d["metrics"]:
        raise ValueError(f"unknown or unsupported metric '{name}' for {dataset}. Available: {list(d['metrics'])}")
    return d["metrics"][name]


def build_filters(dataset: str, filters: dict | None) -> tuple[str, dict]:
    """{'city_type': 'Urban'} -> (' AND city_type = %(f0)s', {'f0': 'Urban'}); dimensions are whitelisted."""
    sql, params = "", {}
    for i, (dim, value) in enumerate((filters or {}).items()):
        sql += f" AND {dim_expr(dataset, dim)} = %(f{i})s"
        params[f"f{i}"] = str(value)
    return sql, params


def identifiers(dataset: str, metric_name: str, dim: str | None = None, filters: dict | None = None) -> tuple[dict, dict]:
    d, m = get(dataset), metric(dataset, metric_name)
    fsql, fparams = build_filters(dataset, filters)
    ids = dict(table=d["table"], base=d["base"], period=d["period"], num=m["num"], den=m["den"], filters=fsql)
    if dim:
        ids["dim"] = dim_expr(dataset, dim)
    return ids, fparams


def provenance(dataset: str) -> dict:
    d = get(dataset)
    out = {"REAL": [], "DERIVED": [], "SYNTHETIC": []}
    for k, (_, p) in d["dims"].items():
        out[p].append(f"{k} (dimension)")
    for k, m in d["metrics"].items():
        out[m["prov"]].append(f"{k} (metric: {m['desc']})")
    for k, p in d.get("other_fields", {}).items():
        out[p.split()[0]].append(f"{k}" + (f" ({p.split(' ', 1)[1].strip('()')})" if " " in p else ""))
    return out
